/**
 * FM エンジンが実行時に構築するテーブル群 (サイン / 対数→線形 / LFO 深度 /
 * キーフラクション)。初回使用時に一度だけ構築する (fmgen.cpp の MakeTable /
 * MakeLFOTable 相当。移植元: FmTables.Build.cs)。
 */
/** サイン位相 (10bit) → 対数レベル。LSB が後半波を選択する。 */
export const SineTable = new Uint32Array(OpSinEnts);

/** 対数 (EG+TL) レベル → 線形出力。 */
export const ClTable = new Int32Array(ClEnts);

/** チャンネル PMS レベルごとの位相変調深度: [type][level][LFO 位相]。 */
export const PmTable: number[][][] = buildJagged(2, 8);

/** 演算子 AMS レベルごとの振幅変調深度: [type][level][LFO 位相]。 */
export const AmTable: number[][][] = buildJagged(2, 4);

/** キーフラクション (16.16 固定小数点、100/64 セント刻み)。 */
export const KfTable = new Int32Array(64);

/** すべての実行時テーブルを一度だけ構築する (冪等)。 */
let tablesBuilt = false;

export function buildFmTables(): void {
  if (tablesBuilt) {
    return;
  }

  tablesBuilt = true;

  // 対数表: 2^(13 - i/256) を 4 の倍数へ丸め、正負のペアで格納。
  // 最初のオクターブ以降は 512 エントリごとにレベルが半分 (-6dB 刻み)。
  for (let i = 0; i < 256; i++) {
    let v = Math.floor(Math.pow(2.0, 13.0 - i / 256.0));
    v = (v + 2) & ~3;
    ClTable[2 * i] = v;
    ClTable[2 * i + 1] = -v;
  }

  for (let i = 512; i < ClEnts; i++) {
    ClTable[i] = (ClTable[i - 512] / 2) | 0;
  }

  // サイン表: 前半に偶数エントリ、後半に奇数エントリを置き、
  // 格納値の LSB で後半波をエンコードする。
  for (let i = 0; i < OpSinEnts / 2; i++) {
    const r = ((i * 2 + 1) * Math.PI) / OpSinEnts;
    const q = (-256.0 * Math.log(Math.sin(r))) / Math.log(2.0);
    const s = Math.floor(q + 0.5) + 1;
    SineTable[i] = (s * 2) >>> 0;
    SineTable[OpSinEnts / 2 + i] = (s * 2 + 1) >>> 0;
  }

  // LFO 変調深度 (MakeLFOTable)。OPM は type 1 行を使用。
  const depth = [
    0, 1 / 360.0, 2 / 360.0, 3 / 360.0, 4 / 360.0, 6 / 360.0, 12 / 360.0, 24 / 360.0, // OPNA
    0, 1 / 480.0, 2 / 480.0, 4 / 480.0, 10 / 480.0, 20 / 480.0, 80 / 480.0, 140 / 480.0, // OPM
  ];
  const amt = [31, 2, 1, 0];

  for (let type = 0; type < 2; type++) {
    for (let level = 0; level < 8; level++) {
      const pmb = depth[type * 8 + level];
      for (let j = 0; j < LfoEnts; j++) {
        const w = 0.6 * pmb * Math.sin((2 * j * Math.PI) / LfoEnts) + 1;
        PmTable[type][level][j] = (0x10000 * (w - 1)) | 0;
      }
    }

    for (let level = 0; level < 4; level++) {
      for (let j = 0; j < LfoEnts; j++) {
        AmTable[type][level][j] = (((j * 4) >> amt[level]) * 2) << 2;
      }
    }
  }

  // キーフラクション: 2^(i/768) の 16.16 固定小数点。
  for (let i = 0; i < 64; i++) {
    KfTable[i] = (0x10000 * Math.pow(2.0, i / 768.0)) | 0;
  }
}

function buildJagged(typeCount: number, levelCount: number): number[][][] {
  const table: number[][][] = [];
  for (let type = 0; type < typeCount; type++) {
    const levels: number[][] = [];
    for (let level = 0; level < levelCount; level++) {
      levels.push(new Array<number>(LfoEnts).fill(0));
    }
    table.push(levels);
  }

  return table;
}
